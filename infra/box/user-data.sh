#!/bin/bash
# EC2 user-data for the dilibori single-box host.
# Templated by Terraform (infra/terraform/modules/box).
# shellcheck shell=bash disable=SC2154,SC1091
set -euxo pipefail

export DEBIAN_FRONTEND=noninteractive
ENVIRONMENT="${environment}"
AWS_REGION="${aws_region}"
SECRET_NAME="${secret_name}"
ARTIFACTS_BUCKET="${artifacts_bucket}"
BACKUPS_BUCKET="${backups_bucket}"
MEDIA_BUCKET="${media_bucket}"
DOMAIN="${domain}"
RELEASE_PARAM="${release_param}"
DATA_DEVICE="${data_device_name}"
OPT_ROOT=/opt/dilibori

apt-get update
apt-get install -y ca-certificates curl gnupg jq unzip make amazon-cloudwatch-agent

install -m 0755 -d /etc/apt/keyrings
curl -fsSL https://download.docker.com/linux/ubuntu/gpg | gpg --dearmor -o /etc/apt/keyrings/docker.gpg
chmod a+r /etc/apt/keyrings/docker.gpg
echo "deb [arch=$(dpkg --print-architecture) signed-by=/etc/apt/keyrings/docker.gpg] https://download.docker.com/linux/ubuntu $(. /etc/os-release && echo "$VERSION_CODENAME") stable" \
  > /etc/apt/sources.list.d/docker.list
apt-get update
apt-get install -y docker-ce docker-ce-cli containerd.io docker-compose-plugin docker-buildx-plugin

if ! command -v aws >/dev/null 2>&1; then
  curl -fsSL "https://awscli.amazonaws.com/awscli-exe-linux-x86_64.zip" -o /tmp/awscliv2.zip
  unzip -q /tmp/awscliv2.zip -d /tmp
  /tmp/aws/install
fi

mkdir -p "$OPT_ROOT"
for _ in $(seq 1 60); do
  if [ -b "$DATA_DEVICE" ] || [ -b /dev/nvme1n1 ]; then
    break
  fi
  sleep 2
done
if [ ! -b "$DATA_DEVICE" ] && [ -b /dev/nvme1n1 ]; then
  DATA_DEVICE=/dev/nvme1n1
fi
if [ -b "$DATA_DEVICE" ]; then
  if ! blkid "$DATA_DEVICE" >/dev/null 2>&1; then
    mkfs.ext4 -F "$DATA_DEVICE"
  fi
  UUID="$(blkid -s UUID -o value "$DATA_DEVICE")"
  if ! grep -q "$UUID" /etc/fstab; then
    echo "UUID=$UUID $OPT_ROOT ext4 defaults,nofail 0 2" >> /etc/fstab
  fi
  mount -a || mount "$DATA_DEVICE" "$OPT_ROOT"
fi

mkdir -p "$OPT_ROOT"/{releases,docker,data/media,data/db,caddy-data/logs,logs,backups}
chmod 755 "$OPT_ROOT"

mkdir -p /etc/docker
cat >/etc/docker/daemon.json <<EOF
{
  "data-root": "$OPT_ROOT/docker",
  "log-driver": "json-file",
  "log-opts": { "max-size": "10m", "max-file": "3" }
}
EOF
systemctl enable docker
systemctl restart docker

mkdir -p /etc/dilibori
SECRET_JSON="$(aws secretsmanager get-secret-value --region "$AWS_REGION" --secret-id "$SECRET_NAME" --query SecretString --output text)"
{
  echo "# Generated by user-data; do not edit by hand."
  echo "AWS_REGION=$AWS_REGION"
  echo "PLATFORM_BOX_ENV=$ENVIRONMENT"
  echo "ARTIFACTS_BUCKET=$ARTIFACTS_BUCKET"
  echo "BACKUPS_BUCKET=$BACKUPS_BUCKET"
  echo "MEDIA_BUCKET=$MEDIA_BUCKET"
  echo "DOMAIN=$DOMAIN"
  echo "RELEASE_PARAM=$RELEASE_PARAM"
  echo "$SECRET_JSON" | jq -r 'to_entries[] | "\(.key)=\(.value)"'
} >/etc/dilibori/box.env
chmod 0600 /etc/dilibori/box.env

mkdir -p /usr/local/lib/dilibori
ln -sfn "$OPT_ROOT/releases/current/infra/box" /usr/local/lib/dilibori/box || true

cat >/etc/cron.d/dilibori <<EOF
SHELL=/bin/bash
PATH=/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin
* * * * * root [ -x /usr/local/lib/dilibori/box/health-metrics.sh ] && /usr/local/lib/dilibori/box/health-metrics.sh >>$OPT_ROOT/logs/health.log 2>&1
15 4 * * * root [ -x /usr/local/lib/dilibori/box/backup.sh ] && /usr/local/lib/dilibori/box/backup.sh >>$OPT_ROOT/logs/backup.log 2>&1
EOF
chmod 644 /etc/cron.d/dilibori

SHA="$(aws ssm get-parameter --region "$AWS_REGION" --name "$RELEASE_PARAM" --query Parameter.Value --output text 2>/dev/null || true)"
if [ -n "$SHA" ] && [ "$SHA" != "bootstrap" ]; then
  aws s3 cp "s3://$ARTIFACTS_BUCKET/releases/$SHA.tar.gz" /tmp/dilibori-release.tar.gz
  mkdir -p "$OPT_ROOT/releases/$SHA"
  tar -xzf /tmp/dilibori-release.tar.gz -C "$OPT_ROOT/releases/$SHA"
  ln -sfn "$OPT_ROOT/releases/$SHA" "$OPT_ROOT/releases/current"
  ln -sfn "$OPT_ROOT/releases/current/infra/box" /usr/local/lib/dilibori/box
  /usr/local/lib/dilibori/box/deploy.sh "$SHA" || true
fi

echo "user-data complete env=$ENVIRONMENT"
